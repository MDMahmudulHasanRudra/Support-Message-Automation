// Reporting reliability

/** What the loader counted while reading the period (only messages inside the period). */
export interface ReliabilityCounts {
  /** Stored `Message` rows: every account's copy of every group message, joins and leaves excluded. */
  storedCopies: number;
  /** One per real message after collapsing the copies (the Team Report's own dedup). */
  logicalMessages: number;
  /** Logical messages by who sent them. */
  byActor: Record<IntelActor, number>;
  /** How each team-member message was matched to its member — the attribution strength. */
  attribution: { idAndPhone: number; idOnly: number; phoneOnly: number };
  /** Staff messages whose identifiers name two members, or one shared by several: nobody credited. */
  conflicting: number;
  /** Distinct senders behind the unattributed staff messages. */
  unattributedSenders: number;
}

export const emptyActorCounts = (): Record<IntelActor, number> => ({
  CUSTOMER: 0,
  MEMBER: 0,
  MEMBER_UNMAPPED: 0,
  OPERATOR: 0,
  AI: 0,
  RULE: 0,
  BROADCAST: 0,
  BUSINESS_PHONE: 0,
});

export interface ReportingReliability extends ReliabilityCounts {
  /** Copies that were collapsed — the same message stored by more than one of our numbers. */
  duplicateCopies: number;
  byCategory: Record<ReplyCategory, number>;
  gaps: { total: number; incomplete: number; recoveredMessages: number };
  /** Dhaka days in the period, and how many may be missing messages or are unverified. */
  days: { total: number; incomplete: number; unverified: number };
}

const DAY_MS = 86_400_000;

export function computeReportingReliability(
  counts: ReliabilityCounts,
  health: Pick<DataHealth, "gaps" | "unverified">,
  period: { start: number; end: number; now: number },
): ReportingReliability {
  const byCategory = Object.fromEntries(REPLY_CATEGORIES.map((c) => [c, 0])) as Record<ReplyCategory, number>;
  for (const [actor, n] of Object.entries(counts.byActor) as Array<[IntelActor, number]>) byCategory[replyCategoryOf(actor)] += n;

  // Dhaka days: the period always starts at a Dhaka midnight; step a day at a time.
  let total = 0;
  let incomplete = 0;
  let unverified = 0;
  for (let dayStart = period.start; dayStart < period.end; dayStart += DAY_MS) {
    const dayEnd = Math.min(dayStart + DAY_MS, period.end);
    total += 1;
    if (health.gaps.some((g) => gapIsIncomplete(g) && g.startedAt < dayEnd && (g.endedAt ?? period.now) > dayStart)) incomplete += 1;
    if (health.unverified && dayStart < health.unverified.to && dayEnd > health.unverified.from) unverified += 1;
  }

  return {
    ...counts,
    duplicateCopies: Math.max(0, counts.storedCopies - counts.logicalMessages),
    byCategory,
    gaps: {
      total: health.gaps.length,
      incomplete: health.gaps.filter((g) => gapIsIncomplete(g)).length,
      recoveredMessages: health.gaps.reduce((sum, g) => sum + (g.recoveredCount ?? 0), 0),
    },
    days: { total, incomplete, unverified },
  };
}

/** One line of the reliability section — the page and the Excel sheet render the same lines. */
export interface ReliabilityLine {
  section: "First observed response" | "First reply came from" | "Automated response" | "First human response" | "Messages" | "Who sent them" | "Attribution" | "Collection" | "Collection detail";
  label: string;
  value: number | string;
  note: string;
}

const secondsText = (s: number | null) => (s === null ? "—" : formatHoursMinutes(s));

/** The three response measures as lines, each section defined in its first line's note. */
export function responseLines(m: ResponseMetrics): ReliabilityLine[] {
  const f = m.firstResponse;
  const lines: ReliabilityLine[] = [
    { section: "First observed response", label: "Customer waits", value: f.waits, note: "Any reply ends a wait — a person's, the AI's, a rule's or the business number's. The figures above use this." },
    { section: "First observed response", label: "Answered within the threshold", value: f.within, note: "" },
    { section: "First observed response", label: "Answered after the threshold", value: f.late, note: "Recall." },
    { section: "First observed response", label: "Never answered, past the threshold", value: f.never, note: `In ${f.unansweredGroups} group(s).` },
    { section: "First observed response", label: "Still inside the threshold", value: f.pending, note: `In ${f.pendingGroups} group(s).` },
    { section: "First observed response", label: "Median wait", value: secondsText(f.medianSeconds), note: `90th percentile ${secondsText(f.p90Seconds)}.` },
  ];
  for (const category of REPLY_CATEGORIES_OF_REPLIES) {
    lines.push({ section: "First reply came from", label: REPLY_CATEGORY_LABELS[category], value: m.firstReplyBy[category], note: "" });
  }
  if (m.firstReplyBy.UNCLASSIFIED > 0) {
    lines.push({ section: "First reply came from", label: "Not classified", value: m.firstReplyBy.UNCLASSIFIED, note: "Replies read without their send record." });
  }
  lines.push(
    { section: "Automated response", label: "Waits first answered by the AI or a rule", value: m.automated.waits, note: "These count as answered above; a person may still have needed to reply." },
    { section: "Automated response", label: "Median automated response", value: secondsText(m.automated.medianSeconds), note: `90th percentile ${secondsText(m.automated.p90Seconds)}.` },
    { section: "First human response", label: "Waits for a person", value: m.human.waits, note: "Human Response SLA's wait: only a person's reply ends it, and a closing remark opens none." },
    { section: "First human response", label: "Ended by a verified person", value: m.human.answeredVerified, note: "A team member, or a signed-in dashboard user." },
    { section: "First human response", label: "Median time to a verified person", value: secondsText(m.human.medianSeconds), note: `90th percentile ${secondsText(m.human.p90Seconds)}.` },
    { section: "First human response", label: "Ended by a person nobody could name", value: m.human.answeredUnverified, note: "The business phone, or staff the roster cannot name." },
    { section: "First human response", label: "Automation replied first, then a person", value: m.human.afterAutomation, note: "" },
    { section: "First human response", label: "On time / late", value: `${m.human.onTime} / ${m.human.late}`, note: "Against the same threshold as the waits above." },
    { section: "First human response", label: "No person yet, past / inside the threshold", value: `${m.human.missed} / ${m.human.pending}`, note: "" },
  );
  return lines;
}

/**
 * The reliability section as lines, in reading order. Counts are printed as counts; no line combines
 * them into a score, because any weighting would be a judgement presented as a measurement.
 */
export function reliabilityLines(r: ReportingReliability): ReliabilityLine[] {
  const lines: ReliabilityLine[] = [
    { section: "Messages", label: "Stored message records", value: r.storedCopies, note: "Every account's copy of every group message in the period (joins and leaves excluded)." },
    { section: "Messages", label: "Logical messages", value: r.logicalMessages, note: "After collapsing copies — what every figure on this report counts." },
    { section: "Messages", label: "Duplicate copies collapsed", value: r.duplicateCopies, note: "The same message stored by more than one of our numbers." },
  ];
  for (const category of REPLY_CATEGORIES) {
    lines.push({ section: "Who sent them", label: REPLY_CATEGORY_LABELS[category], value: r.byCategory[category], note: "" });
  }
  lines.push(
    { section: "Attribution", label: "Matched on WhatsApp id and phone", value: r.attribution.idAndPhone, note: "Strongest: both identifiers name the same member." },
    { section: "Attribution", label: "Matched on WhatsApp id only", value: r.attribution.idOnly, note: "" },
    { section: "Attribution", label: "Matched on phone number only", value: r.attribution.phoneOnly, note: "" },
    { section: "Attribution", label: "Conflicting identities", value: r.conflicting, note: "Identifiers naming two members, or shared by several: counted as staff, credited to nobody." },
    { section: "Attribution", label: "Unidentified staff senders", value: r.unattributedSenders, note: "Distinct senders stamped as staff whom the roster cannot name (includes conflicts and former members)." },
    { section: "Collection", label: "Collection gaps", value: r.gaps.total, note: "Times a number was not collecting during the period." },
    { section: "Collection", label: "Gaps that may have lost messages", value: r.gaps.incomplete, note: "Still open, or not fully recovered." },
    { section: "Collection", label: "Messages recovered after gaps", value: r.gaps.recoveredMessages, note: "" },
    { section: "Collection", label: "Days that may be missing messages", value: `${r.days.incomplete} of ${r.days.total}`, note: "A day touched by a gap that may have lost messages." },
    { section: "Collection", label: "Unverified days", value: `${r.days.unverified} of ${r.days.total}`, note: "Before the project's reporting verified-from date, missing messages cannot be ruled out." },
  );
  return lines;
}
