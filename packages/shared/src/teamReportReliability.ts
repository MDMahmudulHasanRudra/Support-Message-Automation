/**
 * Team Report — who replied, and how far the figures can be trusted (Phase 2, PHASE2.md Stage 7).
 *
 * Every existing Team Report figure is unchanged: a wait still ends at the first reply of ANY kind,
 * the business number's included. What this adds sits BESIDE those figures and never replaces one:
 *
 *   - Who sent each reply, in six categories, from evidence only. An outgoing message is AI, a rule or
 *     a broadcast only when it echoes an `OutboundMessage` that says so (`outgoingActorFor`); one that
 *     echoes nothing was sent outside this system. Direction alone never decides authorship.
 *   - Three response measures, each defined once:
 *       first observed response  the Team Report's own wait — any reply closes it (Response SLA's
 *                                `responseStats`, so the two pages agree);
 *       automated response       the waits whose closing reply was the AI or a rule;
 *       first human response     Human Response SLA's wait (`humanWaits`): only a person's reply ends
 *                                it, and a closing remark opens none. Its time is measured to a
 *                                VERIFIED person — a roster member or a signed-in dashboard user.
 *   - Reporting reliability: explicit counts (stored copies, logical messages, attribution strength,
 *     unidentified staff, collection gaps, incomplete days). Never one invented accuracy percentage.
 */

export const REPLY_CATEGORIES = [
  "CUSTOMER",
  "HUMAN_TEAM_MEMBER",
  "AUTOMATED_AI",
  "AUTOMATED_RULE",
  "OTHER_BUSINESS_REPLY",
  "UNKNOWN_OR_UNATTRIBUTED",
] as const;
export type ReplyCategory = (typeof REPLY_CATEGORIES)[number];
/** The categories a reply can be in — everything but CUSTOMER. */
export type ReplyCategoryOfReply = Exclude<ReplyCategory, "CUSTOMER">;
export const REPLY_CATEGORIES_OF_REPLIES = REPLY_CATEGORIES.filter((c): c is ReplyCategoryOfReply => c !== "CUSTOMER");

export const REPLY_CATEGORY_LABELS: Record<ReplyCategory, string> = {
  CUSTOMER: "Customer",
  HUMAN_TEAM_MEMBER: "Verified person (team member, or a dashboard user)",
  AUTOMATED_AI: "AI",
  AUTOMATED_RULE: "Automation rule",
  OTHER_BUSINESS_REPLY: "Business number — a broadcast, or sent outside this system",
  UNKNOWN_OR_UNATTRIBUTED: "Team member who could not be identified",
};

/**
 * The category of one message's sender.
 *
 * - A roster member on their own WhatsApp, and a dashboard user pressing send (a MANUAL_REPLY row with
 *   who pressed it), are verified people.
 * - A message from the business number that matches no send of ours is "other": somebody on the
 *   business phone, or an alert the worker posted — a person very likely, but nobody this system can
 *   name, so never a verified human reply.
 * - A sender stamped as staff that the roster cannot credit (CONFLICT, AMBIGUOUS, a former member) is
 *   unattributed: staff for safety, nobody for credit.
 */
export function replyCategoryOf(actor: IntelActor): ReplyCategory {
  switch (actor) {
    case "CUSTOMER":
      return "CUSTOMER";
    case "MEMBER":
    case "OPERATOR":
      return "HUMAN_TEAM_MEMBER";
    case "AI":
      return "AUTOMATED_AI";
    case "RULE":
      return "AUTOMATED_RULE";
    case "BROADCAST":
    case "BUSINESS_PHONE":
      return "OTHER_BUSINESS_REPLY";
    case "MEMBER_UNMAPPED":
      return "UNKNOWN_OR_UNATTRIBUTED";
  }
}

/** A reply from a person this system can name. */
export const isVerifiedHumanActor = (actor: IntelActor): boolean => actor === "MEMBER" || actor === "OPERATOR";
/** A reply the system generated by itself. */
export const isAutomatedActor = (actor: IntelActor): boolean => actor === "AI" || actor === "RULE";

// ---------------------------------------------------------------------------------------------
// Response measures

export interface ResponseMetrics {
  /** First observed valid response — the Team Report's waits, any reply closing one. */
  firstResponse: ResponseStats & {
    /** Groups with a wait nobody answered, past its threshold. */
    unansweredGroups: number;
    /** Groups with a wait still inside its threshold. */
    pendingGroups: number;
  };
  /** Who sent the reply that closed each answered wait. UNCLASSIFIED: the caller gave no provenance. */
  firstReplyBy: Record<ReplyCategoryOfReply | "UNCLASSIFIED", number>;
  /** Waits whose closing reply was the AI or a rule, and how fast it came. */
  automated: { waits: number; medianSeconds: number | null; p90Seconds: number | null };
  /** Human Response SLA's waits (`humanWaits`) in the same groups. */
  human: {
    waits: number;
    /** Ended by a verified person. */
    answeredVerified: number;
    /** Ended by a person nobody could name: the business phone, or unidentified staff. */
    answeredUnverified: number;
    onTime: number;
    late: number;
    missed: number;
    pending: number;
    /** Time to a verified person's first reply, over the waits a verified person ended. */
    medianSeconds: number | null;
    p90Seconds: number | null;
    /** Automation replied first, and a person still had to. */
    afterAutomation: number;
  };
}

const emptyFirstReplyBy = (): ResponseMetrics["firstReplyBy"] => ({
  HUMAN_TEAM_MEMBER: 0,
  AUTOMATED_AI: 0,
  AUTOMATED_RULE: 0,
  OTHER_BUSINESS_REPLY: 0,
  UNKNOWN_OR_UNATTRIBUTED: 0,
  UNCLASSIFIED: 0,
});

/**
 * The response measures for one report. `inScope` limits both kinds of wait to the same groups —
 * the groups the report's waits are counted in (all of them, or the ones a scoped Team/member
 * supported) — so the human figure never covers a different set of conversations than the rest.
 */
export function computeResponseMetrics(input: {
  waits: readonly ReportWait[];
  humanWaits: readonly HumanWait[];
  inScope?: ((groupKey: string) => boolean) | null;
}): ResponseMetrics {
  const keep = input.inScope ?? (() => true);
  const waits = input.waits.filter((w) => keep(w.groupKey));
  const human = input.humanWaits.filter((w) => keep(w.groupKey));

  const firstReplyBy = emptyFirstReplyBy();
  const automatedTimes: number[] = [];
  for (const wait of waits) {
    if (wait.repliedAt === null) continue;
    if (!wait.repliedByActor) {
      firstReplyBy.UNCLASSIFIED += 1;
      continue;
    }
    const category = replyCategoryOf(wait.repliedByActor);
    // A wait is only ever closed by a reply, so CUSTOMER cannot occur; counted as unclassified if it did.
    if (category === "CUSTOMER") firstReplyBy.UNCLASSIFIED += 1;
    else firstReplyBy[category] += 1;
    if (isAutomatedActor(wait.repliedByActor) && wait.waitSeconds !== null) automatedTimes.push(wait.waitSeconds);
  }
  automatedTimes.sort((a, b) => a - b);

  const verifiedTimes: number[] = [];
  let answeredVerified = 0;
  let answeredUnverified = 0;
  let afterAutomation = 0;
  const status = { onTime: 0, late: 0, missed: 0, pending: 0 };
  for (const wait of human) {
    if (wait.status === "ON_TIME") status.onTime += 1;
    else if (wait.status === "LATE") status.late += 1;
    else if (wait.status === "MISSED") status.missed += 1;
    else status.pending += 1;
    if (!wait.repliedBy) continue;
    if (wait.automatedFirstAt !== null) afterAutomation += 1;
    if (isVerifiedHumanActor(wait.repliedBy.actor)) {
      answeredVerified += 1;
      if (wait.waitSeconds !== null) verifiedTimes.push(wait.waitSeconds);
    } else {
      answeredUnverified += 1;
    }
  }
  verifiedTimes.sort((a, b) => a - b);

  return {
    firstResponse: {
      ...responseStats(waits),
      unansweredGroups: new Set(waits.filter((w) => w.status === "MISSED").map((w) => w.groupKey)).size,
      pendingGroups: new Set(waits.filter((w) => w.status === "PENDING").map((w) => w.groupKey)).size,
    },
    firstReplyBy,
    automated: { waits: automatedTimes.length, medianSeconds: median(automatedTimes), p90Seconds: percentile(automatedTimes, 0.9) },
    human: {
      waits: human.length,
      answeredVerified,
      answeredUnverified,
      ...status,
      medianSeconds: median(verifiedTimes),
      p90Seconds: percentile(verifiedTimes, 0.9),
      afterAutomation,
    },
  };
}

